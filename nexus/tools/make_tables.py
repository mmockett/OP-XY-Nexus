#!/usr/bin/env python3
"""Writes ../tables.h: the engine's lookup tables, from the formulas of the voice
(the CS-80-style model the engine follows). Pure Python; run it after changing a formula.

    python3 tools/make_tables.py
"""
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent
SR = 44100.0


def row(name, kind, values, per=8):
    lines = [f"static const {kind} {name}[{len(values)}] = {{"]
    for k in range(0, len(values), per):
        lines.append("    " + ", ".join(str(v) for v in values[k:k + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def ratio(ring):
    """The ring modulator's frequency ratio, which rises with ring: a fifth (1.5) up to
    ring 25, 3.5 at ring 70 (bells), 4 at full."""
    if ring <= 0.25:
        return 1.5
    if ring <= 0.70:
        return 1.5 + (ring - 0.25) / 0.45 * 2.0
    return 3.5 + (ring - 0.70) / 0.30 * 0.5


tables = [
    "// Generated by tools/make_tables.py: do not edit.",
    "#pragma once",
    "#include <opxy/types.hpp>",
    "",
    "namespace nexus { namespace tables {",
    "// 2^(k/32), k = 0..32, Q29",
    row("exp2", "opxy::i32", [round(2 ** (k / 32) * 2 ** 29) for k in range(33)]),
    "// The state-variable filter's g = tan(pi f / fs) at f = 20 Hz x 2^(k/4), k = 0..39, Q28",
    row("tangent", "opxy::i32", [round(math.tan(math.pi * 20 * 2 ** (k / 4) / SR) * 2 ** 28) for k in range(40)]),
    "// A first-order allpass's coefficient (t - 1) / (t + 1), t = tan(pi f / fs), at the same f, Q31",
    row("allpass", "opxy::i32", [round((lambda t: (t - 1) / (t + 1))(math.tan(math.pi * 20 * 2 ** (k / 4) / SR)) * 2 ** 31) for k in range(40)]),
    "// Half the detune, Q16 octaves: 30 cents x d^1.5 between the layers, d = k/16",
    row("detune", "opxy::i32", [round(30 * (k / 16) ** 1.5 / 2400 * 65536) for k in range(17)]),
    "// log2 of the ring modulator's ratio, Q16 octaves, ring = k/16",
    row("ratio", "opxy::i32", [round(math.log2(ratio(k / 16)) * 65536) for k in range(17)]),
    "}}",
]
(HERE / "tables.h").write_text("\n".join(tables) + "\n")
print("tables.h written")
